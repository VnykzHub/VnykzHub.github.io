/**
 * Generates the LLM Atlas article content from the original standalone app.
 *
 *   node scripts/generate-atlas-content.mjs
 *
 * Source:  scripts/vendor/atlas-logic.js  (verbatim copy of the original)
 * Emits:   src/content/atlas/atlas.data.ts   — SECTIONS / APPENDIX / GLOSSARY
 *          src/content/atlas/atlas.anims.ts  — the 41 canvas figures
 *
 * Why a generator rather than a one-time paste: the original app is the only
 * copy of this content, and re-running this is the cheapest way to pick up
 * edits to it. Both outputs are committed so the build needs no codegen step.
 */

import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
import vm from 'node:vm'

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..')
const SRC = path.join(ROOT, 'scripts/vendor/atlas-logic.js')
const OUT_DIR = path.join(ROOT, 'src/content/atlas')

const BANNER = `// AUTO-GENERATED by scripts/generate-atlas-content.mjs — do not edit by hand.
// Source: scripts/vendor/atlas-logic.js
`

const lines = fs.readFileSync(SRC, 'utf8').split(/\r?\n/)

const findLine = (pred, from = 0) => {
  for (let i = from; i < lines.length; i++) if (pred(lines[i], i)) return i
  throw new Error('marker not found')
}

// ── 1. Data: everything up to and including the GLOSSARY array literal ──────

const glossaryStart = findLine((l) => l.startsWith('const GLOSSARY'))
const glossaryEnd = findLine((l) => l.trim() === '];', glossaryStart)

const sandbox = { console }
vm.createContext(sandbox)
vm.runInContext(
  lines.slice(0, glossaryEnd + 1).join('\n') +
    '\n;globalThis.__out = { SECTIONS, APPENDIX, GLOSSARY };',
  sandbox
)
const { SECTIONS, APPENDIX, GLOSSARY } = sandbox.__out

/**
 * Repair over-escaped TeX.
 *
 * A handful of equations in the source were written with doubled backslashes
 * ("\\\\mathbf{v}" in the JS literal), so the runtime string carries a literal
 * `\\` before the command. In TeX `\\` is a line break, which left KaTeX
 * rendering "mathbfv" as plain text instead of a bold v.
 *
 * The collapse is only safe where `\\` cannot legitimately mean "new row", so
 * equations containing an environment (bmatrix, cases, aligned…) are left
 * exactly as they are — the RoPE rotation matrix depends on those row breaks.
 */
function fixTex(tex) {
  if (/\\begin\{/.test(tex)) return tex
  return tex.replace(/\\\\([a-zA-Z])/g, '\\$1')
}

for (const section of SECTIONS) {
  for (const sub of section.subs) {
    if (sub.math?.eqs) for (const eq of sub.math.eqs) eq.t = fixTex(eq.t)
  }
}

// The source marks absent optional fields as `anim: null` / `math: null`.
// Dropping the key entirely keeps the emitted data assignable to the optional
// properties on AtlasSub without widening every type to `| null`.
const dropNulls = (_key, value) => (value === null ? undefined : value)

const emit = (value) => JSON.stringify(value, dropNulls, 2)

const dataOut = `${BANNER}
import type { AtlasSection } from './types'

export const ATLAS_SECTIONS: AtlasSection[] = ${emit(SECTIONS)}
`

fs.writeFileSync(path.join(OUT_DIR, 'atlas.data.ts'), dataOut)

// Bibliography and glossary are only needed by /writing, and are small — but
// they must not live in atlas.data.ts, or importing them would pull in every
// article body alongside.
const refsOut = `${BANNER}
import type { AtlasPaperCategory, GlossaryEntry } from './types'

export const ATLAS_PAPERS: AtlasPaperCategory[] = ${emit(APPENDIX.cats)}

export const ATLAS_GLOSSARY: GlossaryEntry[] = ${emit(GLOSSARY)}
`

fs.writeFileSync(path.join(OUT_DIR, 'atlas.refs.ts'), refsOut)

// ── 1b. Metadata: everything the cards and the index page need, minus bodies ─
//
// atlas.data.ts is ~200 kB of prose. The home page's writing teaser and the
// /writing card grid only need titles and counts, so those ship separately —
// otherwise linking to an article from the home page drags every article's
// full text into the home page's bundle.

const meta = SECTIONS.map((s) => {
  let wordCount = 0
  let figureCount = 0
  let equationCount = 0

  for (const sub of s.subs) {
    wordCount += sub.title.split(/\s+/).filter(Boolean).length
    wordCount += sub.body.split(/\s+/).filter(Boolean).length
    if (sub.anim) figureCount++
    if (sub.math) equationCount += sub.math.eqs.length
    if (sub.code) wordCount += sub.code.text.split('\n').length * 4
  }

  return {
    id: s.id,
    label: s.label,
    title: s.title,
    color: s.color,
    icon: s.icon,
    subCount: s.subs.length,
    wordCount,
    figureCount,
    equationCount,
  }
})

const metaOut = `${BANNER}
import type { AtlasMeta } from './types'

export const ATLAS_META: AtlasMeta[] = ${emit(meta)}
`

fs.writeFileSync(path.join(OUT_DIR, 'atlas.meta.ts'), metaOut)

// ── 2. Animations: the ANIMS object, recoloured to the portfolio palette ────

// The original Atlas palette was indigo/mint on near-black. Figures render on
// --panel, which is warm-dark in BOTH themes (instrument panel on paper), so
// the animations keep a single dark-surface palette — no runtime theming
// needed. These substitutions only realign the hues with the site's accents.
const COLOR_MAP = [
  // primary: indigo -> cyan
  ['#6C63FF', '#00D9FF'],
  ['108,99,255', '0,217,255'],
  // mint -> emerald
  ['#00C9A7', '#10B981'],
  ['0,201,167', '16,185,129'],
  ['#00B894', '#10B981'],
  ['0,200,100', '16,185,129'],
  ['#55EFC4', '#4FD1B8'],
  // yellow -> amber
  ['#F7B731', '#F0B84C'],
  ['247,183,49', '240,184,76'],
  ['#FDCB6E', '#F0B84C'],
  // lavender -> purple
  ['#A29BFE', '#8B5CF6'],
  ['162,155,254', '139,92,246'],
  // reds/oranges -> a single coral
  ['#FF6B6B', '#E0705C'],
  ['255,107,107', '224,112,92'],
  ['#E17055', '#E0705C'],
  ['225,112,85', '224,112,92'],
  ['255,0,0', '224,112,92'],
  // pink -> muted rose
  ['#FD79A8', '#C77DBB'],
  ['253,121,168', '199,125,187'],
  // light blue
  ['#74B9FF', '#6BC5DB'],
  // text ramp -> ink tokens
  ['#e8eaf0', '#E8E2D9'],
  ['#c8d0e8', '#D9D3CC'],
  ['#b0b8d0', '#D9D3CC'],
  ['#9aa3bf', '#9D968E'],
  ['#6b7394', '#9D968E'],
  // structural greys -> rule / panel tokens
  ['#2a3050', '#3A342E'],
  ['42,48,80', '58,52,46'],
  ['#1f2535', '#2A2622'],
  ['#3a4060', '#3A342E'],
  ['#1a2828', '#24211D'],
  ['24,28,36', '26,23,20'],
  ['22,26,36', '26,23,20'],
  // fonts
  ["'JetBrains Mono'", "'IBM Plex Mono'"],
]

const animsStart = findLine((l) => l.startsWith('const ANIMS='))

/**
 * Find the line closing the ANIMS object by balancing braces. A naive
 * "first `};`" scan stops at the first nested arrow-function body and silently
 * drops two thirds of the animations — including several the articles
 * reference. Brace counting ignores braces inside strings and comments.
 */
const animsEnd = (() => {
  let depth = 0
  for (let i = animsStart; i < lines.length; i++) {
    const line = lines[i]
      .replace(/\\./g, '')
      .replace(/'[^']*'|"[^"]*"|`[^`]*`/g, '')
      .replace(/\/\/.*$/, '')
    for (const ch of line) {
      if (ch === '{') depth++
      else if (ch === '}' && --depth === 0) return i
    }
  }
  throw new Error('ANIMS object never closes')
})()

let animsBody = lines.slice(animsStart, animsEnd + 1).join('\n')
for (const [from, to] of COLOR_MAP) animsBody = animsBody.split(from).join(to)

// `const ANIMS={` -> a typed export
animsBody = animsBody.replace(
  /^const ANIMS=\{/,
  'export const ATLAS_ANIMS: Record<string, AtlasAnim> = {'
)

// The outer closures are contextually typed by Record<string, AtlasAnim>, but
// their *inner* helpers are loose JS lifted verbatim — 27 implicit-any and
// arithmetic-on-union errors. Annotating 760 lines of someone else's canvas
// drawing buys no safety (nothing outside calls into it; the figure component
// already wraps every draw in try/catch) and would have to be redone on every
// regeneration. The file opts out wholesale instead. Scoped to this one
// generated module — the hand-written atlas.anims.extra.ts is fully checked.
const animsOut = `/* eslint-disable -- vendored source, see the note in the generator */
// @ts-nocheck
${BANNER}import type { AtlasAnim } from './types'

/** Rounded-rect path helper, lifted from the original Atlas. */
function rr(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
) {
  ctx.beginPath()
  ctx.roundRect(x, y, w, h, r)
}

${animsBody}
`

fs.writeFileSync(path.join(OUT_DIR, 'atlas.anims.ts'), animsOut)

// ── 3. Report ───────────────────────────────────────────────────────────────

const subs = SECTIONS.flatMap((s) => s.subs)
const animKeys = [...animsBody.matchAll(/^ {2}([A-Za-z_0-9]+)\s*:\s*\(ctx/gm)].map((m) => m[1])

// Figures the original referenced but never defined are supplied by hand in
// atlas.anims.extra.ts. Anything outside both sets is a real dangling figure.
const extraSrc = fs.readFileSync(path.join(OUT_DIR, 'atlas.anims.extra.ts'), 'utf8')
const extraKeys = [...extraSrc.matchAll(/^const ([A-Za-z_0-9]+): AtlasAnim/gm)].map((m) => m[1])

const missing = [...new Set(subs.map((s) => s.anim).filter(Boolean))].filter(
  (a) => !animKeys.includes(a) && !extraKeys.includes(a)
)

// Every equation must actually parse. KaTeX in strict mode turns a silent
// "renders as garbage" into a build-time failure.
const { default: katex } = await import('katex')
const texErrors = []
let eqCount = 0
for (const section of SECTIONS) {
  for (const sub of section.subs) {
    for (const eq of sub.math?.eqs ?? []) {
      eqCount++
      try {
        katex.renderToString(eq.t, { displayMode: true, throwOnError: true })
      } catch (err) {
        texErrors.push(`${section.id} / ${eq.l}: ${err.message.split('\n')[0]}`)
      }
    }
  }
}

console.log(`sections   ${SECTIONS.length}`)
console.log(`subs       ${subs.length}`)
console.log(`animations ${animKeys.length}`)
console.log(`papers     ${APPENDIX.cats.reduce((n, c) => n + c.papers.length, 0)}`)
console.log(`glossary   ${GLOSSARY.length}`)
console.log(`equations  ${eqCount} (${texErrors.length} failed to parse)`)
if (missing.length) console.error(`MISSING ANIMS: ${missing.join(', ')}`)
if (texErrors.length) {
  console.error('\nTEX ERRORS:')
  for (const e of texErrors) console.error(`  ${e}`)
}
const rel = path.relative(ROOT, OUT_DIR).replace(/\\/g, '/')
console.log(`\nwrote ${rel}/{atlas.data,atlas.meta,atlas.refs,atlas.anims}.ts`)
