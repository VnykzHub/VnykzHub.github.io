/**
 * Builds the AI Engineering Atlas from markdown.
 *
 *   node scripts/generate-ai-atlas.mjs        (npm run gen:ai-atlas)
 *
 * Source:  content-src/ai-engineering-atlas/NN-*.md
 * Emits:   src/content/ai-engineering-atlas/atlas.data.ts
 *          src/content/ai-engineering-atlas/atlas.meta.ts
 *
 * Why markdown rather than the vendored-JS route the LLM Atlas took: that Atlas
 * already existed as an app, and its generator's job was extraction. This one is
 * written from nothing, by many hands, in parallel. Markdown is the format a
 * drafting agent can produce without knowing anything about the site.
 *
 * The generator validates as it goes and FAILS LOUDLY, writing nothing if any
 * check trips. The equivalent checks in generate-atlas-content.mjs caught three
 * real bugs in the LLM Atlas — two thirds of the figures unreachable, a figure
 * referencing an animation that never existed, and five equations rendering as
 * literal text. Silence is the enemy: a page that renders blank looks fine in a
 * build log.
 */

import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
import katex from 'katex'

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..')
const SRC_DIR = path.join(ROOT, 'content-src/ai-engineering-atlas')
const OUT_DIR = path.join(ROOT, 'src/content/ai-engineering-atlas')

const BANNER = `// AUTO-GENERATED by scripts/generate-ai-atlas.mjs — do not edit by hand.
// Source: content-src/ai-engineering-atlas/
`

const REQUIRED_FRONTMATTER = ['id', 'label', 'title', 'slug', 'icon', 'dek']

const errors = []
const warnings = []
const fail = (msg) => errors.push(msg)

/** kebab-case slug from a heading, for stable subsection anchors. */
const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')

// ── Frontmatter ─────────────────────────────────────────────────────────────

function parseFrontmatter(raw, file) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  if (!match) {
    fail(`${file}: missing frontmatter block`)
    return { meta: {}, body: raw }
  }

  const meta = {}
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim()) continue
    const i = line.indexOf(':')
    if (i < 0) {
      fail(`${file}: unparseable frontmatter line: ${line}`)
      continue
    }
    const key = line.slice(0, i).trim()
    let value = line.slice(i + 1).trim()
    // Strip matching quotes so colours like "#F0B84C" survive without needing a
    // real YAML parser to know that # is not a comment inside a quoted scalar.
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    meta[key] = value
  }

  for (const key of REQUIRED_FRONTMATTER) {
    if (!meta[key]) fail(`${file}: frontmatter is missing "${key}"`)
  }

  return { meta, body: raw.slice(match[0].length) }
}

// ── Directive blocks ────────────────────────────────────────────────────────
//
//   :::figure <id>      caption lines           :::
//   :::math <label>     TeX                     :::
//   :::code <lang>      source                  :::
//
// Directives are lifted out of the body first. What remains is prose for the
// Prose renderer, whose grammar is paragraphs, lists, tables, callouts and
// inline code.

const DIRECTIVE = /^:::(figure|math|code)[ \t]*(.*)$/

function extractDirectives(bodyLines, ctx) {
  const prose = []
  let anim
  const eqs = []
  let code

  for (let i = 0; i < bodyLines.length; i++) {
    const m = bodyLines[i].match(DIRECTIVE)
    if (!m) {
      prose.push(bodyLines[i])
      continue
    }

    const [, kind, arg] = m
    const inner = []
    let j = i + 1
    while (j < bodyLines.length && bodyLines[j].trim() !== ':::') inner.push(bodyLines[j++])

    if (j >= bodyLines.length) {
      fail(`${ctx}: ":::${kind}" block is never closed`)
      break
    }
    i = j

    if (kind === 'figure') {
      if (!arg.trim()) fail(`${ctx}: ":::figure" needs an id`)
      else if (anim) fail(`${ctx}: more than one figure in a subsection`)
      else anim = arg.trim()
      continue
    }

    if (kind === 'math') {
      const tex = inner.join('\n').trim()
      if (!tex) {
        fail(`${ctx}: ":::math" block is empty`)
        continue
      }
      // Strict mode, as the LLM Atlas generator does. An equation that fails
      // here renders as literal text in the article — invisible in a build log,
      // glaring to a reader.
      try {
        katex.renderToString(tex, { throwOnError: true, strict: 'error', displayMode: true })
      } catch (err) {
        fail(`${ctx}: TeX failed to parse — ${err.message.split('\n')[0]}\n      ${tex}`)
      }
      eqs.push({ l: arg.trim() || 'Equation', t: tex })
      continue
    }

    // code
    const text = inner.join('\n').replace(/\s+$/, '')
    if (!text) fail(`${ctx}: ":::code" block is empty`)
    else if (code) fail(`${ctx}: more than one code block in a subsection`)
    else code = { lang: arg.trim() || 'python', text }
  }

  return { prose: prose.join('\n').trim(), anim, eqs, code }
}

// ── Parse one section file ──────────────────────────────────────────────────

function parseSection(file) {
  const raw = fs.readFileSync(path.join(SRC_DIR, file), 'utf8')
  const { meta, body } = parseFrontmatter(raw, file)

  const lines = body.split(/\r?\n/)
  const subs = []
  let current = null
  const seenSubIds = new Set()

  const flush = () => {
    if (!current) return
    const ctx = `${file} > ${current.title}`
    const { prose, anim, eqs, code } = extractDirectives(current.lines, ctx)
    if (!prose) fail(`${ctx}: subsection has no prose`)

    const sub = { id: current.id, title: current.title, body: prose }
    if (anim) sub.anim = anim
    if (eqs.length) sub.math = { eqs }
    if (code) sub.code = code
    subs.push(sub)
    current = null
  }

  for (const line of lines) {
    const heading = line.match(/^##\s+(.*)$/)
    if (heading) {
      flush()
      const title = heading[1].trim()
      let id = slugify(title)
      if (seenSubIds.has(id)) {
        fail(`${file}: duplicate subsection heading "${title}"`)
        id = `${id}-${seenSubIds.size}`
      }
      seenSubIds.add(id)
      current = { id, title, lines: [] }
      continue
    }
    if (current) current.lines.push(line)
    else if (line.trim()) warnings.push(`${file}: prose before the first "##" heading is dropped`)
  }
  flush()

  if (!subs.length) fail(`${file}: no "##" subsections found`)

  return {
    file,
    meta,
    section: {
      id: meta.id,
      label: meta.label,
      title: meta.title,
      color: meta.color || '#F0B84C',
      icon: meta.icon,
      subs,
    },
  }
}

// ── Run ─────────────────────────────────────────────────────────────────────

if (!fs.existsSync(SRC_DIR)) {
  console.error(`No source directory: ${path.relative(ROOT, SRC_DIR)}`)
  process.exit(1)
}

const files = fs
  .readdirSync(SRC_DIR)
  .filter((f) => f.endsWith('.md') && /^\d/.test(f))
  .sort()

if (!files.length) {
  console.error(`No NN-*.md files in ${path.relative(ROOT, SRC_DIR)}`)
  process.exit(1)
}

const parsed = files.map(parseSection)

// Cross-file uniqueness. A duplicate slug silently shadows a route.
for (const key of ['id', 'slug']) {
  const seen = new Map()
  for (const { file, meta } of parsed) {
    if (!meta[key]) continue
    if (seen.has(meta[key])) {
      fail(`duplicate ${key} "${meta[key]}" in ${file} and ${seen.get(meta[key])}`)
    }
    seen.set(meta[key], file)
  }
}

if (errors.length) {
  console.error(`\n${errors.length} error(s):\n`)
  for (const e of errors) console.error(`  x ${e}`)
  console.error('\nNothing written.\n')
  process.exit(1)
}

const sections = parsed.map((p) => p.section)

// Figures are declared by drafting agents but implemented later, by hand, so an
// unimplemented one is not an error while the series is in progress.
// AtlasFigure renders a labelled placeholder for an unknown id.
const declaredFigures = sections.flatMap((s) => s.subs.filter((x) => x.anim).map((x) => x.anim))

const emit = (v) => JSON.stringify(v, null, 2)

fs.mkdirSync(OUT_DIR, { recursive: true })

fs.writeFileSync(
  path.join(OUT_DIR, 'atlas.data.ts'),
  `${BANNER}
import type { AtlasSection } from '../llm-atlas/types'

export const AI_ATLAS_SECTIONS: AtlasSection[] = ${emit(sections)}
`
)

const meta = sections.map((s, i) => {
  let wordCount = 0
  let figureCount = 0
  let equationCount = 0
  for (const sub of s.subs) {
    wordCount += `${sub.title} ${sub.body}`.split(/\s+/).filter(Boolean).length
    if (sub.anim) figureCount++
    if (sub.math) equationCount += sub.math.eqs.length
    if (sub.code) wordCount += sub.code.text.split('\n').length * 4
  }
  return {
    id: s.id,
    label: s.label,
    title: s.title,
    color: s.color,
    icon: s.icon,
    slug: parsed[i].meta.slug,
    dek: parsed[i].meta.dek,
    subCount: s.subs.length,
    wordCount,
    figureCount,
    equationCount,
  }
})

fs.writeFileSync(
  path.join(OUT_DIR, 'atlas.meta.ts'),
  `${BANNER}
import type { AtlasMeta } from '../llm-atlas/types'

/** Section meta plus the routing fields the registry needs. */
export interface AiAtlasMeta extends AtlasMeta {
  slug: string
  dek: string
}

export const AI_ATLAS_META: AiAtlasMeta[] = ${emit(meta)}
`
)

const verifyCount = sections.reduce(
  (n, s) => n + s.subs.filter((x) => /<!--\s*VERIFY/i.test(x.body)).length,
  0
)

console.log(`
sections   ${sections.length}
subs       ${sections.reduce((n, s) => n + s.subs.length, 0)}
figures    ${declaredFigures.length} declared
equations  ${meta.reduce((n, m) => n + m.equationCount, 0)} (all parse)
words      ${meta.reduce((n, m) => n + m.wordCount, 0)}
`)

if (verifyCount) {
  console.log(`!  ${verifyCount} subsection(s) carry VERIFY markers — unresolved claims.\n`)
}
for (const w of new Set(warnings)) console.log(`!  ${w}`)

console.log(`wrote ${path.relative(ROOT, OUT_DIR).replace(/\\/g, '/')}/atlas.{data,meta}.ts`)
